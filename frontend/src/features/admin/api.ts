import { api } from '../../shared/api/client';
import { toQuery } from '../../shared/api/endpoints';
import type { Order, OrderSummary, Page } from '../../shared/api/types';
import type {
  AdminCampaign,
  AdminCategory,
  AdminOffer,
  AdminPartner,
  AdminPlan,
  AdminProduct,
  AdminReferral,
  AdminTask,
  AdminTier,
  AdminUser,
  AuditEntry,
  CampaignRequest,
  CategoryRequest,
  ComponentRequest,
  ImpactPreview,
  OfferRequest,
  PartnerPerformance,
  PartnerRequest,
  PriceBreakdown,
  ProductRequest,
  RedemptionResult,
  SettingsKey,
  TaskRequest,
  VariantMetrics,
} from './types';

const post = <T,>(path: string, body?: unknown) => api<T>(`/admin${path}`, { method: 'POST', body: body ?? {} });
const put = <T,>(path: string, body: unknown) => api<T>(`/admin${path}`, { method: 'PUT', body });
const get = <T,>(path: string) => api<T>(`/admin${path}`);

export const adminApi = {
  categories: () => get<AdminCategory[]>('/categories'),
  saveCategory: (id: string | undefined, body: CategoryRequest) => (id ? put<AdminCategory>(`/categories/${id}`, body) : post<AdminCategory>('/categories', body)),
  partners: () => get<AdminPartner[]>('/partners'),
  savePartner: (id: string | undefined, body: PartnerRequest) => (id ? put<AdminPartner>(`/partners/${id}`, body) : post<AdminPartner>('/partners', body)),
  partnerPerformance: (id: string) => get<PartnerPerformance>(`/partners/${id}/performance`),
  products: () => get<AdminProduct[]>('/products'),
  product: (id: string) => get<AdminProduct>(`/products/${id}`),
  saveProduct: (id: string | undefined, body: ProductRequest) => (id ? put<AdminProduct>(`/products/${id}`, body) : post<AdminProduct>('/products', body)),
  adjustInventory: (id: string, delta: number, reason: string) => post<AdminProduct>(`/products/${id}/inventory-adjustments`, { delta, reason }),
  offers: () => get<AdminOffer[]>('/offers'),
  offer: (id: string) => get<AdminOffer>(`/offers/${id}`),
  saveOffer: (id: string | undefined, body: OfferRequest) => (id ? put<AdminOffer>(`/offers/${id}`, body) : post<AdminOffer>('/offers', body)),
  marginPreview: (body: { offerId?: string; sellingPrice: number; components: ComponentRequest[] }) => post<PriceBreakdown>('/offers/margin-preview', body),
  changeOfferStatus: (id: string, action: 'publish' | 'pause' | 'archive') => post<AdminOffer>(`/offers/${id}/${action}`),
  campaigns: () => get<AdminCampaign[]>('/campaigns'),
  saveCampaign: (id: string | undefined, body: CampaignRequest) => (id ? put<AdminCampaign>(`/campaigns/${id}`, body) : post<AdminCampaign>('/campaigns', body)),
  users: (query: string, page: number) => get<Page<AdminUser>>(`/users${toQuery({ query, page, size: 20 })}`),
  assignPlus: (id: string, reason: string, endsAt?: string) => post<AdminUser>(`/users/${id}/membership`, { reason, endsAt }),
  revokePlus: (id: string, reason: string) => post<AdminUser>(`/users/${id}/membership/revoke`, { reason }),
  suspend: (id: string, reason: string) => post<AdminUser>(`/users/${id}/suspend`, { reason }),
  reactivate: (id: string) => post<AdminUser>(`/users/${id}/reactivate`),
  revokeSessions: (id: string) => post<void>(`/users/${id}/revoke-sessions`),
  adjustPoints: (id: string, points: number, reason: string) => post<AdminUser>(`/users/${id}/loyalty-adjustments`, { points, reason }),
  tasks: () => get<AdminTask[]>('/loyalty/tasks'),
  saveTask: (id: string | undefined, body: TaskRequest) => (id ? put<AdminTask>(`/loyalty/tasks/${id}`, body) : post<AdminTask>('/loyalty/tasks', body)),
  tiers: () => get<AdminTier[]>('/loyalty/tiers'),
  saveTiers: (body: AdminTier[]) => put<AdminTier[]>('/loyalty/tiers', body),
  referrals: () => get<AdminReferral[]>('/referrals'),
  approveReferral: (id: string) => post<AdminReferral>(`/referrals/${id}/approve`),
  rejectReferral: (id: string, reason: string) => post<AdminReferral>(`/referrals/${id}/reject`, { reason }),
  plans: () => get<AdminPlan[]>('/membership/plans'),
  savePlan: (code: string, features: string[]) => put<AdminPlan>(`/membership/plans/${code}`, { features }),
  settings: (key: SettingsKey) => get<Record<string, unknown>>(`/settings/${key}`),
  saveSettings: (key: SettingsKey, body: unknown) => put<Record<string, unknown>>(`/settings/${key}`, body),
  impactPreview: (key: 'pricing' | 'loyalty', body: unknown) => post<ImpactPreview>(`/settings/${key}/impact-preview`, body),
  orders: (status: string, query: string, page: number) => get<Page<OrderSummary>>(`/orders${toQuery({ status, query, page, size: 20 })}`),
  order: (id: string) => get<Order>(`/orders/${id}`),
  refund: (id: string, orderItemIds: string[] | undefined, reason: string) => post<Order>(`/orders/${id}/refunds`, { orderItemIds, reason }),
  redeem: (code: string) => post<RedemptionResult>('/redemptions/redeem', { code }),
  auditLogs: (action: string, targetType: string, page: number) => get<Page<AuditEntry>>(`/audit-logs${toQuery({ action, targetType, page, size: 50 })}`),
  metrics: () => get<VariantMetrics[]>('/recommendations/metrics'),
};
