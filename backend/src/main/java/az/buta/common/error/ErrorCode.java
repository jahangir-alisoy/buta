package az.buta.common.error;

import org.springframework.http.HttpStatus;

public enum ErrorCode {
    VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
    AUTH_REQUIRED(HttpStatus.UNAUTHORIZED),
    FORBIDDEN(HttpStatus.FORBIDDEN),
    CSRF_INVALID(HttpStatus.FORBIDDEN),
    ORIGIN_NOT_ALLOWED(HttpStatus.FORBIDDEN),
    PROFILE_INCOMPLETE(HttpStatus.FORBIDDEN),
    NOT_FOUND(HttpStatus.NOT_FOUND),
    METHOD_NOT_ALLOWED(HttpStatus.METHOD_NOT_ALLOWED),
    RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS),
    OTP_INVALID(HttpStatus.BAD_REQUEST),
    OTP_LOCKED(HttpStatus.TOO_MANY_REQUESTS),
    USERNAME_TAKEN(HttpStatus.CONFLICT),
    EMAIL_UNAVAILABLE(HttpStatus.CONFLICT),
    OFFER_UNAVAILABLE(HttpStatus.CONFLICT),
    OFFER_NOT_SELLABLE(HttpStatus.CONFLICT),
    PLUS_REQUIRED(HttpStatus.FORBIDDEN),
    INSUFFICIENT_INVENTORY(HttpStatus.CONFLICT),
    QUANTITY_LIMIT(HttpStatus.UNPROCESSABLE_ENTITY),
    CART_EMPTY(HttpStatus.UNPROCESSABLE_ENTITY),
    CART_LIMIT(HttpStatus.UNPROCESSABLE_ENTITY),
    INSUFFICIENT_POINTS(HttpStatus.UNPROCESSABLE_ENTITY),
    POINTS_REDEMPTION_LIMIT(HttpStatus.UNPROCESSABLE_ENTITY),
    POINTS_REDEMPTION_NOT_ALLOWED(HttpStatus.FORBIDDEN),
    ORDER_STATE_INVALID(HttpStatus.CONFLICT),
    REFUND_NOT_ALLOWED(HttpStatus.UNPROCESSABLE_ENTITY),
    MARGIN_RULE_FAILED(HttpStatus.UNPROCESSABLE_ENTITY),
    PUBLISH_RULE_FAILED(HttpStatus.UNPROCESSABLE_ENTITY),
    FILE_TYPE_NOT_ALLOWED(HttpStatus.BAD_REQUEST),
    FILE_TOO_LARGE(HttpStatus.BAD_REQUEST),
    IDEMPOTENCY_KEY_REQUIRED(HttpStatus.BAD_REQUEST),
    IDEMPOTENCY_CONFLICT(HttpStatus.CONFLICT),
    INVALID_REFERRAL_CODE(HttpStatus.UNPROCESSABLE_ENTITY),
    WEIGHTS_INVALID(HttpStatus.UNPROCESSABLE_ENTITY),
    CONFLICT(HttpStatus.CONFLICT),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }

    public HttpStatus status() {
        return status;
    }
}
